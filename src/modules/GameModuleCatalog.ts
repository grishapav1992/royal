export type IndependentGameId = typeof GAME_MODULES[number]['gameId'];
export interface GameModuleContract {
 readonly gameId: IndependentGameId;
 readonly slug: string;
 readonly apiVersion: 1;
 readonly rulesVersion: number;
 readonly progressVersion: number;
}
export const GAME_MODULE_CATALOG = Object.freeze(Object.fromEntries(
 GAME_MODULES.map(contract => [contract.gameId, Object.freeze(contract)]),
)) as Readonly<Record<IndependentGameId, GameModuleContract>>;

export function gameModuleContract(gameId: string): GameModuleContract | undefined {
 return Object.hasOwn(GAME_MODULE_CATALOG, gameId) ? GAME_MODULE_CATALOG[gameId as IndependentGameId] : undefined;
}
