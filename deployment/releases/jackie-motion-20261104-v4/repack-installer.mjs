import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {verifyGithub} from '../../../scripts/release.mjs';
const [installerCommit,outPath]=process.argv.slice(2);assert(/^[a-f0-9]{40}$/.test(installerCommit)&&outPath);
const receipt=await verifyGithub(process.cwd()),out=path.resolve(outPath);
const m=JSON.parse(fs.readFileSync(out+'/install-manifest.json'));
assert.equal(m.sourceCommit,receipt.sourceCommit);
execFileSync('git',['merge-base','--is-ancestor',installerCommit,'origin/main']);
const sha=b=>createHash('sha256').update(b).digest('hex');
const bytes=execFileSync('git',['show',installerCommit+':deployment/releases/jackie-motion-20261104-v4/deploy.py']);
const maintenance=execFileSync('git',['show',installerCommit+':deployment/maintenance/cleanup-release-history.py']);
const tool={applicationSourceCommit:m.sourceCommit,installerSourceCommit:installerCommit,githubMainContainsInstaller:true,sha256:sha(bytes),remoteMain:receipt.remoteMain};
fs.writeFileSync(out+'/deploy.py',bytes);
fs.writeFileSync(out+'/installer-source.json',JSON.stringify(tool,null,2)+'\n');
fs.copyFileSync('module-build/release-github.json',out+'/release-github.json');
for(const n of ['deploy.py','installer-source.json','release-github.json'])m.support[n]=sha(fs.readFileSync(out+'/'+n));
m.maintenanceSha256=sha(maintenance);m.maintenanceSourceCommit=installerCommit;
fs.writeFileSync(out+'/install-manifest.json',JSON.stringify(m,null,2)+'\n');
console.log(JSON.stringify({applicationSourceCommit:m.sourceCommit,installerSourceCommit:installerCommit,version:m.version,maintenanceSha256:m.maintenanceSha256,applicationRebuilt:false}));
