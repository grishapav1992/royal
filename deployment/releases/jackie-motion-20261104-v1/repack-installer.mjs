import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {verifyGithub} from '../../../scripts/release.mjs';
const [installerCommit,payloadPath]=process.argv.slice(2);assert(/^[a-f0-9]{40}$/.test(installerCommit)&&payloadPath);
const root=process.cwd(),receipt=await verifyGithub(root),payload=path.resolve(payloadPath);
const m=JSON.parse(fs.readFileSync(payload+'/install-manifest.json')),app=JSON.parse(fs.readFileSync('module-build/release-manifest.json'));
assert.equal(m.sourceCommit,receipt.sourceCommit);assert.equal(m.sourceCommit,app.sourceCommit);
execFileSync('git',['merge-base','--is-ancestor',installerCommit,'origin/main']);
const bytes=execFileSync('git',['show',installerCommit+':deployment/releases/jackie-motion-20261104-v1/deploy.py']);
const sha=b=>createHash('sha256').update(b).digest('hex');
const tool={applicationSourceCommit:app.sourceCommit,installerSourceCommit:installerCommit,githubMainContainsInstaller:true,sha256:sha(bytes),remoteMain:receipt.remoteMain};
fs.writeFileSync(payload+'/deploy.py',bytes);
const toolBytes=Buffer.from(JSON.stringify(tool,null,2)+'\n');fs.writeFileSync(payload+'/installer-source.json',toolBytes);
const github=fs.readFileSync('module-build/release-github.json');fs.writeFileSync(payload+'/release-github.json',github);
m.support['deploy.py']=sha(bytes);m.support['installer-source.json']=sha(toolBytes);m.support['release-github.json']=sha(github);
fs.writeFileSync(payload+'/install-manifest.json',JSON.stringify(m,null,2)+'\n');
console.log(JSON.stringify({applicationSourceCommit:app.sourceCommit,installerSourceCommit:installerCommit,version:m.version,installerSha256:sha(bytes),applicationRebuilt:false}));
