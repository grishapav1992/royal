export const applyProviderPendingSchemaMigration = (db: PostgresDatabase) => applySchemaMigration(db, {
  id: 'game-provider-pending-v1',
  statements: [
    `CREATE TABLE IF NOT EXISTS capro_pending_balances (
      account_id TEXT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
      pending_units TEXT NOT NULL DEFAULT '0' CHECK(pending_units ~ '^(0|[1-9][0-9]*)$'))`,
    `CREATE TABLE IF NOT EXISTS capro_pending_ledger (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
      operation_id TEXT NOT NULL,
      amount_units TEXT NOT NULL CHECK(amount_units ~ '^(0|-?[1-9][0-9]*)$'),
      pending_balance_units TEXT NOT NULL CHECK(pending_balance_units ~ '^(0|[1-9][0-9]*)$'),
      reason TEXT NOT NULL CHECK(reason IN ('debit','credit','refund','rollback','transfer')),
      created_at BIGINT NOT NULL,
      UNIQUE(account_id,operation_id))`,
  ],
});

// Whole coins remain a compatibility projection. Historical rows missing units used whole coins.
export const applyDemoMoneySchemaMigrations = async (db: PostgresDatabase) => {
  await applySchemaMigration(db, {
  id: 'game-demo-money-v1',
  indexes: [
    { name: 'demo_ledger_account', table: 'demo_ledger', columns: ['account_id', 'id'] },
    { name: 'demo_ledger_time', table: 'demo_ledger', columns: ['account_id', 'created_at'] },
  ],
  statements: [
    'ALTER TABLE demo_wallets ADD COLUMN IF NOT EXISTS fraction_units BIGINT NOT NULL DEFAULT 0 CHECK(fraction_units BETWEEN 0 AND 99)',
    'ALTER TABLE demo_ledger ADD COLUMN IF NOT EXISTS amount_units BIGINT',
    'ALTER TABLE demo_ledger ADD COLUMN IF NOT EXISTS balance_units BIGINT',
    'ALTER TABLE demo_ledger ADD COLUMN IF NOT EXISTS entry_type TEXT',
    "ALTER TABLE demo_ledger ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'royal-coins'",
    'ALTER TABLE demo_ledger ADD COLUMN IF NOT EXISTS game_name TEXT',
    'UPDATE demo_ledger SET amount_units=amount*100 WHERE amount_units IS NULL',
    'UPDATE demo_ledger SET balance_units=balance*100 WHERE balance_units IS NULL',
    'UPDATE demo_ledger SET entry_type=kind WHERE entry_type IS NULL',
    'ALTER TABLE demo_ledger ALTER COLUMN amount_units SET NOT NULL, ALTER COLUMN balance_units SET NOT NULL, ALTER COLUMN entry_type SET NOT NULL',
    'ALTER TABLE demo_ledger ADD CONSTRAINT demo_ledger_amount_units_v1 CHECK(amount_units BETWEEN -100000000000 AND 100000000000)',
    'ALTER TABLE demo_ledger ADD CONSTRAINT demo_ledger_balance_units_v1 CHECK(balance_units BETWEEN 0 AND 100000000000)',
    'ALTER TABLE demo_ledger ADD CONSTRAINT demo_ledger_amount_projection_v1 CHECK(amount=amount_units/100)',
    'ALTER TABLE demo_ledger ADD CONSTRAINT demo_ledger_balance_projection_v1 CHECK(balance=balance_units/100)',
    "ALTER TABLE demo_ledger ADD CONSTRAINT demo_ledger_entry_type_v1 CHECK(entry_type IN ('deposit','bet','win','refund','rollback'))",
    "ALTER TABLE demo_ledger ADD CONSTRAINT demo_ledger_kind_projection_v1 CHECK(kind=CASE WHEN entry_type='refund' THEN 'win' WHEN entry_type='rollback' THEN CASE WHEN amount_units<0 THEN 'bet' ELSE 'win' END ELSE entry_type END)",
  ],
  });
  await applyProviderPendingSchemaMigration(db);
};

