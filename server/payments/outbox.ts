import { createHash } from 'node:crypto';
import { PostgresDatabase } from '../database';
import { amount } from '../crypto/amounts';
import { serviceSignature, validPaymentEvent, type PaymentEvent } from './protocol';

export type LedgerChange = { accountId: string; operationId: string; entryKey: string; available: bigint; reserved: bigint; createdAt: number };
export class PaymentOutbox {
  readonly ready: Promise<void>; private flushing?: Promise<void>;
  constructor(private db: PostgresDatabase, private destination: string, private secret: string, prerequisite: Promise<void> = Promise.resolve(), private fetcher: typeof fetch = fetch) {
    this.ready = prerequisite.then(() => db.exec(`CREATE TABLE IF NOT EXISTS payment_outbox(sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_id TEXT UNIQUE NOT NULL,user_id TEXT NOT NULL,body TEXT NOT NULL,delivered_at BIGINT,attempts BIGINT NOT NULL DEFAULT 0,next_attempt_at BIGINT NOT NULL DEFAULT 0)`));
  }
  async record(change: LedgerChange) {
    if (!this.db.inTransaction) throw new Error('Payment event must share the ledger transaction');
    const kind = change.entryKey.split(':')[0] as PaymentEvent['kind'];
    const event: PaymentEvent = { event_id: createHash('sha256').update(change.entryKey).digest('hex'), user_id: change.accountId,
      payment_id: change.operationId, kind, currency: 'USDT', scale: 6, deposit_amount: kind === 'deposit' ? amount(change.available) : '0',
      available_delta_units: String(change.available), reserved_delta_units: String(change.reserved), created_at: change.createdAt };
    if (!validPaymentEvent(event)) throw new Error('Invalid payment ledger event');
    await this.db.prepare('INSERT INTO payment_outbox(event_id,user_id,body) VALUES (?,?,?) ON CONFLICT DO NOTHING').run(event.event_id, event.user_id, JSON.stringify(event));
  }
  async flush() {
    if (this.flushing) return this.flushing;
    this.flushing = this.deliver().finally(() => { this.flushing = undefined; }); return this.flushing;
  }
  private async deliver() {
    await this.ready;
    for (let i = 0; i < 30; i++) {
      const row = await this.db.prepare(`SELECT current.* FROM payment_outbox current WHERE current.delivered_at IS NULL AND current.next_attempt_at<=?
        AND NOT EXISTS (SELECT 1 FROM payment_outbox previous WHERE previous.user_id=current.user_id AND previous.sequence<current.sequence AND previous.delivered_at IS NULL)
        ORDER BY current.sequence LIMIT 1`).get(Date.now());
      if (!row) return;
      try {
        const url = new URL(this.destination), timestamp = String(Date.now()), body = String(row.body);
        const response = await this.fetcher(url, { method: 'POST', body, redirect: 'error', signal: AbortSignal.timeout(5000), headers: {
          'Content-Type': 'application/json', 'x-royal-payments-timestamp': timestamp,
          'x-royal-payments-signature': serviceSignature(this.secret, 'event', timestamp, 'POST', url.pathname, body),
        } });
        const reply = await response.json() as { ok?: boolean; event_id?: string };
        if (!response.ok || reply.ok !== true || reply.event_id !== row.event_id) throw new Error('Event not acknowledged');
        await this.db.prepare('UPDATE payment_outbox SET delivered_at=? WHERE event_id=? AND delivered_at IS NULL').run(Date.now(), row.event_id);
      } catch {
        const attempts = Number(row.attempts) + 1, delay = Math.min(60000, 1000 * 2 ** Math.min(attempts - 1, 6));
        await this.db.prepare('UPDATE payment_outbox SET attempts=?,next_attempt_at=? WHERE event_id=? AND delivered_at IS NULL').run(attempts, Date.now() + delay, row.event_id);
      }
    }
  }
}
