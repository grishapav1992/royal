import { randomInt } from 'node:crypto';
import type { PostgresDatabase } from './database';
import { DEMO_BETS, type DemoWallet } from '../src/shared/demoWallet';
import { FLIGHT_ENTROPY_SIZE, FLIGHT_MAX_MULTIPLIER, flightAutoCashoutCents, flightMultiplierCentsAt, flightTimeForCents, type FlightOperation, type FlightResult, type FlightSession } from '../src/shared/flightGame';
import { WalletError } from './demoWallet';
import { demoBalanceUnits, MAX_DEMO_UNITS, recordDemoUnits, saveDemoUnits } from './demoWalletAmounts';
import { inputRecord } from './games/types';
import { applyFlightSchemaMigrations, applyFlightRequestIntegrityMigration } from './game-database-migrations';

type StoredFlight = {
  id: string; account_id: string; state: FlightSession['state']; amount: number; auto_cashout_cents: number;
  started_at: number; crash_cents: number; payout_multiplier_cents: number; payout_units: number;
  reserved_units: number; settled_at: number | null; settlement_reason: FlightSession['reason'];
};
const uuid = (value: unknown): value is string => typeof value === 'string' && /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(value);

function operation(value: unknown): FlightOperation {
  try {
    const row = inputRecord(value);
    const expected = row.action === 'start' ? 'action,amount,autoCashout,id' : row.action === 'cashout' ? 'action,id,sessionId' : '';
    if (!expected || !uuid(row.id) || Object.keys(row).sort().join(',') !== expected
      || Reflect.ownKeys(row).length !== expected.split(',').length) throw new Error();
    if (row.action === 'start') {
      if (!Number.isSafeInteger(row.amount) || !(DEMO_BETS as readonly unknown[]).includes(row.amount)) throw new Error();
      const target = flightAutoCashoutCents(row.autoCashout);
      return { id: row.id, action: 'start', amount: row.amount as number, autoCashout: target / 100 };
    }
    if (!uuid(row.sessionId)) throw new Error();
    return { id: row.id, action: 'cashout', sessionId: row.sessionId };
  } catch { throw new WalletError(400, 'Некорректное действие Royal Orbit.'); }
}

/** Uniform integer entropy gives P(survive T) = floor(98 * 2^32 / T) / 2^32. */
export function flightCrashCents(draw: number): number {
  if (!Number.isSafeInteger(draw) || draw < 0 || draw >= FLIGHT_ENTROPY_SIZE) throw new RangeError('Invalid flight randomness');
  return Number((98n * BigInt(FLIGHT_ENTROPY_SIZE) / BigInt(draw + 1)) < 10_000n
    ? 98n * BigInt(FLIGHT_ENTROPY_SIZE) / BigInt(draw + 1) : 10_000n);
}

export class DemoFlightStore {
  readonly ready: Promise<void>;
  constructor(private db: PostgresDatabase, private walletSnapshot: (accountId: string) => Promise<DemoWallet>,
    private otherReserved: (accountId: string) => Promise<number> = async () => 0,
    private draw: (max: number) => number = randomInt, private now: () => number = Date.now, prerequisite: Promise<void> = Promise.resolve()) {
    this.ready = prerequisite.then(() => db.transaction(async () => db.exec(`CREATE TABLE IF NOT EXISTS demo_flight_sessions (
      id TEXT NOT NULL, account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
      sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
      state TEXT NOT NULL CHECK(state IN ('active','lost','cashed_out')),
      amount INTEGER NOT NULL CHECK(amount IN (10,50,100,500)),
      auto_cashout_cents INTEGER NOT NULL CHECK(auto_cashout_cents BETWEEN 110 AND 10000),
      started_at INTEGER NOT NULL, crash_cents INTEGER NOT NULL CHECK(crash_cents BETWEEN 98 AND 10000),
      payout_multiplier_cents INTEGER NOT NULL DEFAULT 0, payout_units INTEGER NOT NULL DEFAULT 0,
      reserved_units INTEGER NOT NULL, settled_at INTEGER, settlement_reason TEXT,
      PRIMARY KEY(account_id,id));
      CREATE UNIQUE INDEX IF NOT EXISTS demo_flight_active ON demo_flight_sessions(account_id) WHERE state='active';
      CREATE TABLE IF NOT EXISTS demo_flight_requests (
      account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE, id TEXT NOT NULL,
      request_key TEXT NOT NULL, session_id TEXT NOT NULL, created_at INTEGER NOT NULL,
      PRIMARY KEY(account_id,id));`))).then(() => applyFlightSchemaMigrations(db)).then(() => applyFlightRequestIntegrityMigration(db));
  }
  async reservedUnits(accountId: string): Promise<number> {
    await this.ready;
    return Number((await this.db.prepare("SELECT reserved_units AS units FROM demo_flight_sessions WHERE account_id=? AND state='active'").get(accountId))?.units ?? 0);
  }
  private clock(): number {
    const now = this.now();
    if (!Number.isSafeInteger(now) || now < 0) throw new Error('Invalid flight clock');
    return now;
  }
  private async session(accountId: string, id: string): Promise<StoredFlight | undefined> {
    return (await this.db.prepare('SELECT * FROM demo_flight_sessions WHERE account_id=? AND id=?').get(accountId, id)) as StoredFlight | undefined;
  }
  private publicSession(row: StoredFlight, now: number): FlightSession {
    const cents = row.state === 'active' ? flightMultiplierCentsAt(row.started_at, now) : row.payout_multiplier_cents;
    return {
      id: row.id, state: row.state, amount: row.amount, autoCashout: row.auto_cashout_cents / 100,
      startedAt: row.started_at, multiplier: cents / 100,
      cashoutValue: row.state === 'active' ? Number(BigInt(row.amount * 100) * BigInt(cents) / 100n) / 100 : row.payout_units / 100,
      payout: row.payout_units / 100, settledAt: row.settled_at, reason: row.settlement_reason,
    };
  }
  private async finish(row: StoredFlight, cents: number, reason: Exclude<FlightSession['reason'], null>, at: number): Promise<StoredFlight> {
    const payout = reason === 'crash' ? 0 : Number(BigInt(row.amount * 100) * BigInt(cents) / 100n);
    const state = reason === 'crash' ? 'lost' : 'cashed_out';
    const balance = await demoBalanceUnits(this.db, row.account_id) + payout;
    if (!Number.isSafeInteger(balance) || balance + await this.otherReserved(row.account_id) > MAX_DEMO_UNITS) throw new Error('Reserved flight payout exceeds wallet capacity');
    (await this.db.prepare('UPDATE demo_flight_sessions SET state=?,payout_multiplier_cents=?,payout_units=?,reserved_units=0,settled_at=?,settlement_reason=? WHERE account_id=? AND id=? AND state=\'active\'')
      .run(state, cents, payout, at, reason, row.account_id, row.id));
    await saveDemoUnits(this.db, row.account_id, balance);
    await recordDemoUnits(this.db, row.account_id, row.id, 'win', payout, balance, 'royal-flight', 'Royal Orbit');
    return { ...row, state, payout_multiplier_cents: cents, payout_units: payout, reserved_units: 0, settled_at: at, settlement_reason: reason };
  }
  private async settleInTransaction(accountId: string, now: number) {
    const row = (await this.db.prepare("SELECT * FROM demo_flight_sessions WHERE account_id=? AND state='active'").get(accountId)) as StoredFlight | undefined;
    if (!row) return;
    if (row.crash_cents >= row.auto_cashout_cents) {
      const deadline = row.started_at + flightTimeForCents(row.auto_cashout_cents);
      if (now >= deadline) await this.finish(row, row.auto_cashout_cents, 'auto', deadline);
    } else {
      const deadline = row.started_at + flightTimeForCents(row.crash_cents + 1);
      if (now >= deadline) await this.finish(row, row.crash_cents, 'crash', deadline);
    }
  }
  async settleDue(accountId: string) {
    await this.ready;
    await this.db.transaction(async () => { await this.settleInTransaction(accountId, this.clock()); }, { lockKey: 'account:' + accountId });
  }
  async snapshot(accountId: string): Promise<FlightResult> {
    await this.ready;
    return this.db.transaction(async () => {
      const now = this.clock();
      await this.settleInTransaction(accountId, now);
      const row = (await this.db.prepare(`WITH active AS (
        SELECT * FROM demo_flight_sessions WHERE account_id=? AND state='active'
      ) SELECT * FROM active UNION ALL (
        SELECT * FROM demo_flight_sessions WHERE account_id=? AND state<>'active'
          AND NOT EXISTS(SELECT 1 FROM active)
        ORDER BY started_at DESC,sequence_id DESC LIMIT 1
      )`).get(accountId, accountId)) as StoredFlight | undefined;
      const result = { wallet: await this.walletSnapshot(accountId), session: row ? this.publicSession(row, now) : null, serverNow: now };
      return result;
    }, { lockKey: 'account:' + accountId });
  }
  async operate(accountId: string, value: unknown): Promise<FlightResult> {
    await this.ready;
    const op = operation(value), key = JSON.stringify(op);
    return this.db.transaction(async () => {
      if(await this.db.prepare('SELECT 1 FROM demo_casino_requests WHERE account_id=? AND id=?').get(accountId,op.id))throw new WalletError(409,'Этот номер операции уже использован в казино.');
      const now = this.clock();
      await this.settleInTransaction(accountId, now);
      const previous = (await this.db.prepare('SELECT request_key,session_id FROM demo_flight_requests WHERE account_id=? AND id=?').get(accountId, op.id));
      if (previous) {
        if (previous.request_key !== key) throw new WalletError(409, 'Нельзя изменить отправленное действие Royal Orbit.');
        const row = await this.session(accountId, String(previous.session_id));
        if (!row) throw new Error('Missing saved flight session');
        const result = { wallet: await this.walletSnapshot(accountId), session: this.publicSession(row, now), serverNow: now };
        return result;
      }
      if ((await this.db.prepare('SELECT 1 FROM demo_operations WHERE account_id=? AND operation_id=?').get(accountId, op.id))
        || (await this.db.prepare('SELECT 1 FROM demo_mines_requests WHERE account_id=? AND id=?').get(accountId, op.id))) throw new WalletError(409, 'Этот идентификатор уже использован.');
      const recent = (await this.db.prepare('SELECT COUNT(*) AS n FROM (SELECT 1 FROM demo_flight_requests WHERE account_id=? AND created_at>? LIMIT 120) recent').get(accountId, now - 60000));
      if (Number(recent!.n) >= 120) throw new WalletError(429, 'Слишком много действий. Подожди минуту.');
      let row: StoredFlight;
      if (op.action === 'start') {
        if ((await this.db.prepare("SELECT 1 FROM demo_flight_sessions WHERE account_id=? AND state='active'").get(accountId))) throw new WalletError(409, 'Сначала заверши текущий полёт.');
        const stake = op.amount * 100, balance = await demoBalanceUnits(this.db, accountId);
        if (balance < stake) throw new WalletError(400, 'Недостаточно демомонет.');
        const reserved = stake * FLIGHT_MAX_MULTIPLIER;
        if (balance - stake + reserved + await this.otherReserved(accountId) > MAX_DEMO_UNITS) throw new WalletError(400, 'Недостаточно места на демобалансе для возможного выигрыша.');
        row = { id: op.id, account_id: accountId, state: 'active', amount: op.amount, auto_cashout_cents: flightAutoCashoutCents(op.autoCashout),
          started_at: now, crash_cents: flightCrashCents(this.draw(FLIGHT_ENTROPY_SIZE)), payout_multiplier_cents: 0,
          payout_units: 0, reserved_units: reserved, settled_at: null, settlement_reason: null };
        (await this.db.prepare('INSERT INTO demo_flight_sessions(id,account_id,state,amount,auto_cashout_cents,started_at,crash_cents,reserved_units) VALUES (?,?,?,?,?,?,?,?)')
          .run(row.id, accountId, row.state, row.amount, row.auto_cashout_cents, row.started_at, row.crash_cents, reserved));
        await saveDemoUnits(this.db, accountId, balance - stake);
        await recordDemoUnits(this.db, accountId, op.id, 'bet', -stake, balance - stake, 'royal-flight', 'Royal Orbit');
        await this.settleInTransaction(accountId, now);
        row = (await this.session(accountId, op.id))!;
      } else {
        const found = await this.session(accountId, op.sessionId);
        if (!found) throw new WalletError(404, 'Полёт не найден.');
        row = found.state === 'active' ? await this.finish(found, flightMultiplierCentsAt(found.started_at, now), 'manual', now) : found;
      }
      (await this.db.prepare('INSERT INTO demo_flight_requests(account_id,id,request_key,session_id,created_at) VALUES (?,?,?,?,?)').run(accountId, op.id, key, row.id, now));
      const result = { wallet: await this.walletSnapshot(accountId), session: this.publicSession(row, now), serverNow: now };
      return result;
    }, { lockKey: 'account:' + accountId });
  }
}
