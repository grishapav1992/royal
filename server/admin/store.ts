import type { PostgresDatabase } from '../database';
import { applySchemaMigration } from '../database-migrations';
import { immutableLedgerTables } from '../finance/pg-ledger-schema';
import { CryptoError } from '../crypto/config';
import { gameAccountId } from '../../src/shared/nileWallet';
import type { FinanceReport } from '../../src/shared/financeAdmin';

export class FinanceCommandRejected extends CryptoError {
  constructor(status:number,message:string,readonly commandId:string){super(status,message);}
}

export class FinanceAdminStore {
  readonly ready:Promise<void>;
  constructor(readonly db:PostgresDatabase, prerequisite:Promise<void>=Promise.resolve()){
    this.ready=prerequisite.then(async()=>{
      await applySchemaMigration(db,{id:'finance-admin-v1',statements:[
        `CREATE TABLE IF NOT EXISTS finance_player_controls(player_id TEXT PRIMARY KEY REFERENCES accounts(id),blocked BOOLEAN NOT NULL,reason TEXT NOT NULL,updated_at BIGINT NOT NULL,actor_id TEXT NOT NULL)`,
        `CREATE TABLE IF NOT EXISTS finance_admin_commands(id TEXT PRIMARY KEY,actor_id TEXT NOT NULL,player_id TEXT NOT NULL REFERENCES accounts(id),source TEXT NOT NULL,action TEXT NOT NULL,
          body TEXT NOT NULL,state TEXT NOT NULL CHECK(state IN ('pending','completed','rejected')),created_at BIGINT NOT NULL,completed_at BIGINT)`,
        `CREATE TABLE IF NOT EXISTS finance_admin_audit(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,command_id TEXT NOT NULL REFERENCES finance_admin_commands(id),
          actor_id TEXT NOT NULL,player_id TEXT NOT NULL,source TEXT NOT NULL,action TEXT NOT NULL,state TEXT NOT NULL,reason TEXT NOT NULL,created_at BIGINT NOT NULL)`,
        `CREATE INDEX IF NOT EXISTS finance_admin_audit_player ON finance_admin_audit(player_id,created_at DESC)`,
      ]});
      await db.transaction(()=>immutableLedgerTables(db,['finance_admin_audit'],'immutable administrative audit'));
    });
  }
  async assertAllowed(playerId:string){
    await this.ready;
    if((await this.db.prepare('SELECT blocked FROM finance_player_controls WHERE player_id=?').get(playerId))?.blocked)
      throw new CryptoError(403,'Денежные операции аккаунта приостановлены администратором.');
  }
  async hasAcceptedCommand(id:string){
    await this.ready;
    return !!await this.db.prepare('SELECT 1 FROM finance_admin_commands WHERE id=?').get(id);
  }
  async search(query:string){
    await this.ready;
    if(query.length>254)throw new CryptoError(400,'Слишком длинный поиск.');
    return this.db.prepare(`SELECT a.id,a.name,a.email,coalesce(c.blocked,false) AS blocked FROM accounts a LEFT JOIN finance_player_controls c ON c.player_id=a.id
      WHERE position(lower(?) in lower(a.id||' '||a.name||' '||a.email))>0 ORDER BY a.created_at DESC,a.id LIMIT 101`).all(query.trim());
  }
  async player(id:string){
    await this.ready;if(!gameAccountId(id))throw new CryptoError(400,'Некорректный игрок.');
    const row=await this.db.prepare(`SELECT a.id,a.name,a.email,a.created_at AS joinedAt,coalesce(c.blocked,false) AS blocked,c.reason AS blockReason
      FROM accounts a LEFT JOIN finance_player_controls c ON c.player_id=a.id WHERE a.id=?`).get(id);
    if(!row)throw new CryptoError(404,'Игрок не найден.');return row;
  }
  async enrich(report:FinanceReport){
    const ids=[...new Set([...report.rows.flatMap(r=>[r.playerId,r.opponentId]),...report.players.map(r=>r.id)])].filter(Boolean);
    const rows=ids.length?await this.db.prepare(`SELECT a.id,a.name,a.email,coalesce(c.blocked,false) AS blocked FROM accounts a LEFT JOIN finance_player_controls c ON c.player_id=a.id WHERE a.id=ANY(?::text[])`).all(ids):[];
    const players=new Map(rows.map(r=>[r.id,r]));
    report.rows=report.rows.map(r=>({...r,playerName:players.get(r.playerId)?.name,playerEmail:players.get(r.playerId)?.email,opponentName:players.get(r.opponentId)?.name,blocked:players.get(r.playerId)?.blocked}));
    report.players=report.players.map(r=>({...r,name:players.get(r.id)?.name,email:players.get(r.id)?.email,blocked:players.get(r.id)?.blocked}));
    return report;
  }
  private async audit(op:any,state:string){
    await this.db.prepare('INSERT INTO finance_admin_audit(command_id,actor_id,player_id,source,action,state,reason,created_at) VALUES(?,?,?,?,?,?,?,?)')
      .run(op.id,op.actorId,op.playerId,op.source,op.action,state,op.reason,Date.now());
  }
  async command(op:{id:string;actorId:string;playerId:string;source:string;action:string;reason:string;[key:string]:unknown},run:()=>Promise<unknown>){
    await this.ready;const body=JSON.stringify(op);
    const completed=await this.db.transaction(async()=>{
      const previous=await this.db.prepare('SELECT * FROM finance_admin_commands WHERE id=?').get(op.id);
      if(previous){if(previous.body!==body)throw new CryptoError(409,'Номер действия уже использован с другими параметрами.');if(previous.state==='rejected')throw new FinanceCommandRejected(409,'Это действие отклонено. Создай новое действие после исправления причины.',op.id);return previous.state==='completed';}
      await this.player(op.playerId);
      await this.db.prepare("INSERT INTO finance_admin_commands(id,actor_id,player_id,source,action,body,state,created_at) VALUES(?,?,?,?,?,?,'pending',?)")
        .run(op.id,op.actorId,op.playerId,op.source,op.action,body,Date.now());
      await this.audit(op,'pending');return false;
    },{lockKey:'admin-commands'});
    if(completed)return{ok:true,replayed:true};
    if(op.action==='block'||op.action==='unblock'){
      return this.db.transaction(async()=>{
        const row=await this.db.prepare('SELECT state FROM finance_admin_commands WHERE id=?').get(op.id);
        if(row?.state==='completed')return{ok:true,replayed:true};
        await this.db.prepare(`INSERT INTO finance_player_controls VALUES(?,?,?,?,?) ON CONFLICT(player_id) DO UPDATE SET blocked=excluded.blocked,reason=excluded.reason,updated_at=excluded.updated_at,actor_id=excluded.actor_id`)
          .run(op.playerId,op.action==='block',op.reason,Date.now(),op.actorId);
        await this.db.prepare("UPDATE finance_admin_commands SET state='completed',completed_at=? WHERE id=?").run(Date.now(),op.id);
        await this.audit(op,'completed');return{ok:true,replayed:false};
      },{lockKey:'admin-commands'});
    }
    try{
      const result=await run();
      await this.db.transaction(async()=>{
        const changed=await this.db.prepare("UPDATE finance_admin_commands SET state='completed',completed_at=? WHERE id=? AND state='pending'").run(Date.now(),op.id);
        if(changed.changes)await this.audit(op,'completed');
      },{lockKey:'admin-commands'});
      return{ok:true,result};
    }catch(error){
      const state=await this.db.transaction(async()=>{
        const rejected=error instanceof CryptoError&&error.status<500;
        if(rejected)await this.db.prepare("UPDATE finance_admin_commands SET state='rejected',completed_at=? WHERE id=? AND state='pending'").run(Date.now(),op.id);
        await this.audit(op,rejected?'rejected':'retry');
        return (await this.db.prepare('SELECT state FROM finance_admin_commands WHERE id=?').get(op.id))?.state;
      },{lockKey:'admin-commands'});
      if(state==='rejected'&&error instanceof CryptoError)throw new FinanceCommandRejected(error.status,error.message,op.id);
      throw error;
    }
  }
  async history(filters:{playerId?:string;from?:number;to?:number;page:number}){
    await this.ready;const args:unknown[]=[],clauses:string[]=[];
    for(const [clause,value]of [['player_id=?',filters.playerId],['created_at>=?',filters.from],['created_at<?',filters.to]] as const)
      if(value!==undefined){clauses.push(clause);args.push(value);}
    const where=clauses.length?' WHERE '+clauses.join(' AND '):'';
    return this.db.transaction(async()=>({
      count:Number((await this.db.prepare('SELECT count(*)::int AS n FROM finance_admin_audit'+where).get(...args))!.n),
      rows:await this.db.prepare('SELECT * FROM finance_admin_audit'+where+' ORDER BY seq DESC LIMIT 25 OFFSET ?').all(...args,(filters.page-1)*25),
    }),{readOnly:true});
  }
}
