type Plan = { [key: string]: unknown; Plans?: Plan[] };
const planNodes = (plan: Plan): Plan[] => [plan, ...(plan.Plans ?? []).flatMap(planNodes)];

test('wallet rate limiting scans at most 120 recent events, preserves history and releases the expired window', async context => {
  const db = await fixture();
  let draws = 0;
  try {
    const wallet = new DemoWalletStore(db, () => { draws++; return 0; });
    await wallet.operate('alice', { id: randomUUID(), kind: 'deposit', amount: 1000 });
    await db.prepare(`INSERT INTO demo_ledger(account_id,operation_id,kind,amount,balance,created_at,amount_units,balance_units,entry_type)
      SELECT 'alice','event-'||n,'win',0,1000,?,0,100000,'win' FROM generate_series(1,10000) n`).run(Date.now());
    await db.exec('ANALYZE demo_ledger');
    const queries: string[] = [], prepare = db.prepare.bind(db);
    context.mock.method(db, 'prepare', (sql: string) => { queries.push(sql); return prepare(sql); });
    await assert.rejects(wallet.operate('alice', { id: randomUUID(), kind: 'spin', amount: 10 }),
      error => error instanceof WalletError && error.status === 429);
    assert.equal(draws, 0);
    assert.equal(await demoBalanceUnits(db, 'alice'), 100000);
    const query = queries.find(sql => sql.startsWith('SELECT COUNT(*) AS n FROM (SELECT 1 FROM demo_ledger'))!;
    const result = await db.prepare('EXPLAIN (ANALYZE,FORMAT JSON) ' + query).get('alice', Date.now() - 60000);
    const nodes = planNodes((result!['QUERY PLAN'] as { Plan: Plan }[])[0].Plan);
    assert.equal(Math.max(...nodes.map(node => Number(node['Actual Rows']))), 120);
    await db.prepare("UPDATE demo_ledger SET created_at=? WHERE operation_id LIKE 'event-%'").run(Date.now() - 60001);
    assert.equal((await wallet.operate('alice', { id: randomUUID(), kind: 'deposit', amount: 1 })).wallet.balance, 1001);
    assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM demo_ledger').get())!.n, 10002);
  } finally { await db.dropSchema(); await db.close(); }
});

test('Flight history uses a bounded index scan and preserves active priority and insertion-order ties', async context => {
  const db = await fixture();
  try {
    const wallet = new DemoWalletStore(db, () => 0, () => 5000);
    await wallet.operate('alice', { id: randomUUID(), kind: 'deposit', amount: 1000 });
    await db.exec(`INSERT INTO demo_flight_sessions(id,account_id,state,amount,auto_cashout_cents,started_at,crash_cents,reserved_units,settled_at,settlement_reason)
      SELECT 'history-'||n,'alice','lost',10,200,n,98,0,n+1,'crash' FROM generate_series(1,10000) n;
      ANALYZE demo_flight_sessions`);
    const tie = randomUUID();
    await db.prepare(`INSERT INTO demo_flight_sessions(id,account_id,state,amount,auto_cashout_cents,started_at,crash_cents,reserved_units,settled_at,settlement_reason)
      VALUES (?,'alice','lost',10,200,10000,98,0,10001,'crash')`).run(tie);
    const queries: string[] = [], prepare = db.prepare.bind(db);
    context.mock.method(db, 'prepare', (sql: string) => { queries.push(sql); return prepare(sql); });
    assert.equal((await wallet.flight.snapshot('alice')).session!.id, tie);
    const historySql = queries.find(sql => sql.startsWith('WITH active AS'))!;
    const explain = async () => {
      const result = await db.prepare('EXPLAIN (ANALYZE,FORMAT JSON) ' + historySql).get('alice', 'alice');
      return planNodes((result!['QUERY PLAN'] as { Plan: Plan }[])[0].Plan);
    };
    const nodes = await explain();
    const historyScan = nodes.find(node => node['Index Name'] === 'demo_flight_history_v1');
    assert(historyScan);
    assert.equal(historyScan['Actual Rows'], 1);
    assert.equal(nodes.some(node => node['Node Type'] === 'Sort'), false);
    const oldPlan = await db.prepare(`EXPLAIN (ANALYZE,FORMAT JSON) SELECT * FROM demo_flight_sessions
      WHERE account_id=? ORDER BY (state='active') DESC,started_at DESC,sequence_id DESC LIMIT 1`).get('alice');
    assert(planNodes((oldPlan!['QUERY PLAN'] as { Plan: Plan }[])[0].Plan).some(node => Number(node['Actual Rows']) >= 10001));
    const start = { id: randomUUID(), action: 'start', amount: 10, autoCashout: 2 };
    await wallet.flight.operate('alice', start);
    assert.equal((await wallet.flight.snapshot('alice')).session!.id, start.id);
    const activeNodes = await explain();
    assert.equal(activeNodes.find(node => node['Index Name'] === 'demo_flight_history_v1')!['Actual Loops'], 0);
    assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM demo_flight_sessions').get())!.n, 10002);
  } finally { await db.dropSchema(); await db.close(); }
});

test('wallet, Flight, Mines and provider operations share the account lock while other players progress', async () => {
  const db = await fixture(), otherDb = new PostgresDatabase(db.schema);
  let release!: () => void, held!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  const started = new Promise<void>(resolve => { held = resolve; });
  try {
    const wallet = new DemoWalletStore(db, () => 0);
    const otherWallet = new DemoWalletStore(otherDb, () => 0), provider = new CasinoApiProWallet(otherDb);
    await Promise.all([wallet.ready, otherWallet.ready, provider.ready]);
    const player = await provider.player('alice');
    await wallet.operate('alice', { id: randomUUID(), kind: 'deposit', amount: 1000 });
    const holding = db.transaction(async () => { held(); await gate; }, { lockKey: 'account:alice' });
    await started;
    let completed = 0;
    const pending = [
      otherWallet.operate('alice', { id: randomUUID(), kind: 'deposit', amount: 1 }),
      otherWallet.flight.operate('alice', { id: randomUUID(), action: 'start', amount: 10, autoCashout: 2 }),
      otherWallet.mines.operate('alice', { id: randomUUID(), action: 'start', amount: 10, mineCount: 1 }),
      provider.callback('debit', { playerId: player, currency: 'USD', transactionId: 'parallel-debit', amount: '0.01' }, 'USD'),
    ].map(async promise => { const result = await promise; completed++; return result; });
    await otherWallet.operate('bob', { id: randomUUID(), kind: 'deposit', amount: 1 });
    assert.equal(completed, 0);
    release(); await Promise.all([holding, ...pending]);
    assert.equal(completed, 4);
    assert.equal(await demoBalanceUnits(db, 'alice'), 98099);
    assert.equal(await demoBalanceUnits(db, 'bob'), 100);
    assert.equal((await wallet.mines.active('alice')).session!.state, 'active');
    assert.equal((await wallet.flight.snapshot('alice')).session!.state, 'active');
  } finally { release?.(); await db.dropSchema(); await Promise.all([db.close(), otherDb.close()]); }
});

test('Flight requests require an existing session owned by the same account and account cleanup preserves other players', async () => {
  const db = await fixture();
  try {
    const wallet = new DemoWalletStore(db, () => 0, () => 5000);
    for (const account of ['alice', 'bob']) await wallet.operate(account, { id: randomUUID(), kind: 'deposit', amount: 1000 });
    const alice = { id: randomUUID(), action: 'start', amount: 10, autoCashout: 2 };
    const bob = { id: randomUUID(), action: 'start', amount: 10, autoCashout: 2 };
    const saved = await wallet.flight.operate('alice', alice);
    await wallet.flight.operate('bob', bob);
    const insert = db.prepare('INSERT INTO demo_flight_requests(account_id,id,request_key,session_id,created_at) VALUES (?,?,?,?,?)');
    for (const session of [bob.id, randomUUID()]) {
      await assert.rejects(insert.run('alice', randomUUID(), '{}', session, 5000),
        error => (error as { code?: string; constraint?: string }).code === '23503'
          && (error as { constraint?: string }).constraint === 'demo_flight_requests_session_v1');
    }
    await assert.rejects(db.prepare('DELETE FROM demo_flight_sessions WHERE account_id=? AND id=?').run('alice', alice.id),
      /demo_flight_requests_session_v1/);
    const reopened = new DemoWalletStore(db, () => { throw new Error('A saved Flight must not draw again'); }, () => 5000);
    assert.deepEqual(await reopened.flight.operate('alice', alice), saved);
    await db.prepare('DELETE FROM accounts WHERE id=?').run('alice');
    assert.equal((await db.prepare("SELECT count(*) AS n FROM demo_flight_requests WHERE account_id='alice'").get())!.n, 0);
    assert.equal((await db.prepare("SELECT count(*) AS n FROM demo_flight_sessions WHERE account_id='alice'").get())!.n, 0);
    assert.equal((await wallet.flight.snapshot('bob')).session!.id, bob.id);
    assert.equal((await db.prepare("SELECT count(*) AS n FROM demo_flight_requests WHERE account_id='bob'").get())!.n, 1);
    const constraint = await db.prepare(`SELECT convalidated,condeferrable,pg_get_constraintdef(oid) AS definition
      FROM pg_constraint WHERE conrelid='demo_flight_requests'::regclass AND conname='demo_flight_requests_session_v1'`).get();
    assert.equal(constraint!.convalidated, true);
    assert.equal(constraint!.condeferrable, false);
    assert.match(constraint!.definition, /FOREIGN KEY \(account_id, session_id\) REFERENCES demo_flight_sessions\(account_id, id\)/);
  } finally { await db.dropSchema(); await db.close(); }
});

