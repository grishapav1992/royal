test('canonical ledger migration preserves whole coins, exact fractional history and saved receipts through reopening', async () => {
  const db = await fixture();
  const receipt = '{ "round": {"symbols":[0,1,2],"bet":10,"payout":0,"multiplier":0} }';
  try {
    await db.exec(legacyTables);
    await db.exec(`CREATE TABLE demo_operations(account_id TEXT NOT NULL,operation_id TEXT NOT NULL,kind TEXT NOT NULL,
      amount BIGINT NOT NULL,result TEXT NOT NULL,PRIMARY KEY(account_id,operation_id));
      INSERT INTO demo_ledger(account_id,operation_id,kind,amount,balance,created_at,amount_units,balance_units,entry_type) VALUES
      ('alice','whole','deposit',100,100,1,NULL,NULL,NULL),
      ('alice','cent','bet',0,99,2,-1,9999,'bet'),
      ('alice','refund','win',0,100,3,1,10000,'refund'),
      ('alice','rollback','bet',0,99,4,-1,9999,'rollback')`);
    await db.prepare('INSERT INTO demo_operations VALUES (?,?,?,?,?)').run('alice', 'saved', 'spin', 10, receipt);
    let wallet = new DemoWalletStore(db);
    await wallet.ready;
    const expected = [
      { operation_id: 'whole', amount_units: 10000, balance_units: 10000, entry_type: 'deposit' },
      { operation_id: 'cent', amount_units: -1, balance_units: 9999, entry_type: 'bet' },
      { operation_id: 'refund', amount_units: 1, balance_units: 10000, entry_type: 'refund' },
      { operation_id: 'rollback', amount_units: -1, balance_units: 9999, entry_type: 'rollback' },
    ];
    assert.deepEqual(await db.prepare('SELECT operation_id,amount_units,balance_units,entry_type FROM demo_ledger ORDER BY id').all(), expected);
    const snapshot = await wallet.snapshot('alice');
    assert.equal(snapshot.balance, 100);
    assert.deepEqual(snapshot.entries.map(row => [row.kind, row.amount, row.balance]),
      [['rollback', -0.01, 99.99], ['refund', 0.01, 100], ['bet', -0.01, 99.99], ['deposit', 100, 100]]);
    const versionCount = (await db.prepare('SELECT COUNT(*) AS n FROM _royal_migrations').get())!.n;
    wallet = new DemoWalletStore(db);
    await wallet.ready;
    assert.deepEqual(await wallet.snapshot('alice'), snapshot);
    assert.deepEqual(await db.prepare('SELECT operation_id,amount_units,balance_units,entry_type FROM demo_ledger ORDER BY id').all(), expected);
    assert.equal((await db.prepare('SELECT result FROM demo_operations WHERE operation_id=?').get('saved'))!.result, receipt);
    assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM _royal_migrations').get())!.n, versionCount);
    await assert.rejects(db.prepare('UPDATE demo_ledger SET amount=2 WHERE operation_id=?').run('cent'), /demo_ledger_amount_projection_v1/);
    await assert.rejects(db.prepare('UPDATE demo_ledger SET balance=1 WHERE operation_id=?').run('cent'), /demo_ledger_balance_projection_v1/);
    await assert.rejects(db.prepare('UPDATE demo_ledger SET kind=? WHERE operation_id=?').run('bet', 'refund'), /demo_ledger_kind_projection_v1/);
    await assert.rejects(db.prepare('UPDATE demo_ledger SET amount_units=NULL WHERE operation_id=?').run('cent'), /not-null constraint/);
    await assert.rejects(db.prepare('UPDATE demo_ledger SET amount=1000000001,amount_units=100000000100 WHERE operation_id=?').run('cent'), /demo_ledger_amount_units_v1/);
  } finally { await db.dropSchema(); await db.close(); }
});

