test('Flight integrity upgrade preserves existing receipts, validates its FK and applies once across reopening', async () => {
  const db = await legacyFlightFixture(), reopened = new PostgresDatabase(db.schema);
  try {
    const receipt = '{ "action": "cashout", "id": "saved", "sessionId": "alice-flight" }';
    await db.prepare('INSERT INTO demo_flight_requests VALUES (?,?,?,?,?)').run('alice', 'saved', receipt, 'alice-flight', 1791446400000);
    const rows = await db.prepare('SELECT * FROM demo_flight_requests').all();
    await applyFlightRequestIntegrityMigration(db);
    await applyFlightRequestIntegrityMigration(reopened);
    assert.deepEqual(await db.prepare('SELECT * FROM demo_flight_requests').all(), rows);
    assert.equal((await db.prepare("SELECT count(*) AS n FROM _royal_migrations WHERE id='game-flight-request-integrity-v1'").get())!.n, 1);
    assert.equal((await db.prepare(`SELECT convalidated FROM pg_constraint
      WHERE conrelid='demo_flight_requests'::regclass AND conname='demo_flight_requests_session_v1'`).get())!.convalidated, true);
    const index = await db.prepare(`SELECT indexdef FROM pg_indexes WHERE schemaname=? AND indexname='demo_flight_requests_session_v1'`).get(db.schema);
    assert.match(index!.indexdef, /\(account_id, session_id\)/);
  } finally { await db.dropSchema(); await Promise.all([db.close(), reopened.close()]); }
});

