import express from 'express';
import { randomUUID } from 'node:crypto';
import { accounts } from '../server/accounts';
import { installAuth } from '../server/authRoutes';
import { installFinanceAdmin } from '../server/admin/routes';
import { installNilePlay } from '../server/nilePlayRoutes';
import { createNilePlayServer } from '../server/finance/nile-play-service';
import { playTestSetup } from '../server-tests/finance/helpers/nile-play-fixture';
import { WALLET_ACCOUNT_HEADER } from '../src/shared/walletAccount';

if(process.env.NODE_ENV!=='test')throw new Error('The admin browser fixture requires an isolated test database');
await accounts.ready;
const owner=await accounts.login('owner@admin-fixture.test','fixture-admin-password'),player=await accounts.login('player@admin-fixture.test','fixture-player-password');
await accounts.rename(owner.account.id,'Владелец');await accounts.rename(player.account.id,'Мария Волкова');
process.env.FINANCE_ADMIN_ACCOUNT_IDS=owner.account.id;
const nile=await playTestSetup(':memory:',()=>Math.floor(Math.random()*5));
await nile.ledger.claim(player.account.id,await nile.ledger.invite('player'));
for(let i=0;i<12;i++)await nile.ledger.spin(player.account.id,{id:randomUUID(),stakeUnits:i%3?'1000000':'2000000'});
const socket=process.platform==='win32'?'\\\\.\\pipe\\royal-admin-'+randomUUID():'/tmp/royal-admin-'+randomUUID()+'.sock';
process.env.NILE_PLAY_SOCKET_FILE=socket;
const financial=createNilePlayServer(nile.ledger);await new Promise<void>(resolve=>financial.listen(socket,resolve));
const app=express();installAuth(app);installFinanceAdmin(app);installNilePlay(app,socket);
app.get('/healthz',(_req,res)=>res.json({ok:true}));
const server=app.listen(2594,'127.0.0.1');
const sync=setInterval(async()=>{try{await nile.ledger.sync(nile.source,await nile.reconciliation());}catch{}},20000);sync.unref();
console.log('Admin fixture ready on 2594 with synthetic accounts and isolated Nile funds.');
const stop=async()=>{clearInterval(sync);server.close();financial.close();await nile.close();await accounts.close();process.exit(0);};
process.once('SIGTERM',()=>void stop());process.once('SIGINT',()=>void stop());
