import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { HEROES, initialTeam, playNeopolisSpin, NEOPOLIS_MATH } from '../../src/shared/neopolisMath.ts';
import { seededRandom } from '../../src/shared/draconaMath.ts';

const seeds = [302710111, 610829303];
const roundsPerSeed = 500000, readyRoundsPerSeed = 4000000, target = .96, scale = 1000000000;
const sourceFiles = ['src/shared/neopolisMath.ts', 'src/shared/draconaMath.ts', 'scripts/game-math/calibrate-neopolis-stakes.mjs'];
const hashes = async () => Object.fromEntries(await Promise.all(sourceFiles.map(async file => [file, createHash('sha256').update(await readFile(file)).digest('hex')])));
const sourceHashes = await hashes(), startedAt = new Date().toISOString(), rows = [], factors = {};
for (const [heroIndex, hero] of HEROES.entries()) {
  const others = HEROES.map((_, index) => index).filter(index => index !== heroIndex);
  factors[hero] = [];
  for (let state = 0; state < 16; state++) {
    const origin = initialTeam(hero); origin.charges[others[0]] = Math.floor(state / 4); origin.charges[others[1]] = state % 4;
    const count = state === 15 ? readyRoundsPerSeed : roundsPerSeed;
    let samples = 0, sum = 0, squared = 0, free = 0;
    const histogram = new Map();
    for (const seed of seeds) {
      const random = seededRandom(seed + heroIndex * 1000003 + state * 7919);
      for (let round = 0; round < count; round++) {
        let team = origin, battle = null, ticks = 0;
        do {
          const result = playNeopolisSpin(team, battle, random, false);
          team = result.team; battle = result.battle; if (result.free) free++;
          assert.equal(result.points % NEOPOLIS_MATH.payNumerator, 0);
          ticks += result.points / NEOPOLIS_MATH.payNumerator;
        } while (battle?.remaining);
        const raw = ticks * NEOPOLIS_MATH.payNumerator / (40 * NEOPOLIS_MATH.payDenominator);
        samples++; sum += raw; squared += raw * raw;
        histogram.set(ticks, (histogram.get(ticks) || 0) + 1);
      }
    }
    const expected = factor => [...histogram].reduce((total, [ticks, frequency]) => total + frequency * Math.min(3000, ticks * NEOPOLIS_MATH.payNumerator / (40 * NEOPOLIS_MATH.payDenominator) * factor), 0) / samples;
    let low = 0, high = 10;
    assert(expected(high) > target);
    for (let i = 0; i < 60; i++) { const mid = (low + high) / 2; if (expected(mid) < target) low = mid; else high = mid; }
    const numerator = Math.floor((low + high) / 2 * scale);
    factors[hero].push(numerator);
    const mean = sum / samples, half = 1.96 * Math.sqrt(Math.max(0, squared - sum * sum / samples) / (samples - 1) / samples);
    rows.push({ hero, state, charges: origin.charges, samples, freeSpins: free, rawReward: sum, rawRewardSquared: squared, rawMean: mean,
      rawInterval95: [mean - half, mean + half], scaleNumerator: numerator, scaleDenominator: scale, calibratedUnroundedReturn: expected(numerator / scale),
      maximumRawReturn: Math.max(...histogram.keys()) * NEOPOLIS_MATH.payNumerator / (40 * NEOPOLIS_MATH.payDenominator),
      histogramSha256: createHash('sha256').update(JSON.stringify([...histogram].sort(([a], [b]) => a - b))).digest('hex') });
    console.log(JSON.stringify({ hero, state, samples, rawMean: mean, payoutScale: numerator / scale }));
  }
}
assert.deepEqual(await hashes(), sourceHashes, 'Calibration engine changed during sampling');
const report = { rulesVersion: 4, target, scale, startedAt, completedAt: new Date().toISOString(), seeds, roundsPerSeed, readyRoundsPerSeed, sourceHashes,
  method: 'Calibration only. Independent complete paid rounds from every public team state, including all free continuations and the 3000x cap. Conditional payout scales equalize the estimated return before integer rounding. Independent qualification seeds and actual integer settlement are required before release.', rows };
await mkdir('docs/game-math', { recursive: true });
await writeFile('docs/game-math/neopolis-v4-calibration.json', JSON.stringify(report, null, 2) + '\n');
const output = `import { HEROES, type Team } from './neopolisMath';\n\n// Generated by calibrate-neopolis-stakes.mjs. This is calibration, not qualification.\nexport const NEOPOLIS_PAYOUT_SCALE = ${scale}n;\nexport const NEOPOLIS_TEAM_PAYOUTS = ${JSON.stringify(factors, null, 2)} as const;\nexport function neopolisTeamState(team: Team) {\n  const others = HEROES.map((_, index) => index).filter(index => index !== HEROES.indexOf(team.starter));\n  return team.charges[others[0]] * 4 + team.charges[others[1]];\n}\nexport function neopolisTeamPayout(team: Team) { return BigInt(NEOPOLIS_TEAM_PAYOUTS[team.starter][neopolisTeamState(team)]); }\n`;
await writeFile('src/shared/neopolisStakePayouts.ts', output);
console.log(JSON.stringify({ complete: true, states: rows.length, samples: rows.reduce((n, row) => n + row.samples, 0) }));
