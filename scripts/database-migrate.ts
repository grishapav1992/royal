import { DatabaseSync } from 'node:sqlite';
import pg from 'pg';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { databaseConfig, identifier, legacyTableSql, rowsDigest, type DatabaseRow } from '../server/database';
import { gameAccountId } from '../src/shared/nileWallet';

type Source = { schema: string; path: string; bindingsPath?: string };
const allowed = new Set(['royal_game', 'royal_tron_reader', 'royal_nile_deposits', 'royal_nile_play', 'royal_mainnet']);

// The only SQLite reader in the application toolchain is this offline importer.
// Writers must be stopped before taking the final source copies.
export async function migrateLegacyDatabases(sources: Source[], reportFile?: string, targetPrefix = '') {
  if (targetPrefix && !/^preview_[a-z0-9_]+_$/.test(targetPrefix)) throw new Error('Invalid migration preview prefix');
  if (!sources.length || new Set(sources.map(s => s.schema)).size !== sources.length || sources.some(s => !allowed.has(s.schema) || (s.bindingsPath && s.schema !== 'royal_nile_deposits'))) {
    throw new Error('Supply unique approved PostgreSQL schemas');
  }
  const pool = new pg.Pool({ ...databaseConfig(), max: 1, statement_timeout: 0 });
  const client = await pool.connect();
  const report: { schema: string; tables: { name: string; count: number; sha256: string }[] }[] = [];
  try {
    await client.query('BEGIN');
    await client.query("SELECT pg_advisory_xact_lock(hashtextextended('royal_database_cutover',0))");
    for (const original of sources) {
      const source = { ...original, schema: targetPrefix + original.schema };
      const sqlite = new DatabaseSync(source.path, { readOnly: true });
      try {
        const integrity = sqlite.prepare('PRAGMA integrity_check').get();
        if (integrity?.integrity_check !== 'ok' || sqlite.prepare('PRAGMA foreign_key_check').all().length) throw new Error('Legacy source failed integrity checks: ' + source.schema);
        const existing = await client.query('SELECT 1 FROM pg_tables WHERE schemaname=$1 LIMIT 1', [source.schema]);
        if (existing.rows.length) throw new Error('Import target is not empty: ' + source.schema);
        await client.query('CREATE SCHEMA IF NOT EXISTS ' + identifier(source.schema));
        await client.query('SET LOCAL search_path TO ' + identifier(source.schema) + ',public');
        const tables = sqlite.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").all();
        const pending = [...tables];
        // Table creation follows foreign key dependencies, independent of source order.
        while (pending.length) {
          let progress = false;
          for (let index = pending.length - 1; index >= 0; index--) {
            const table = pending[index];
            const parents = sqlite.prepare('PRAGMA foreign_key_list(' + identifier(String(table.name)) + ')').all().map(fk => String(fk.table));
            if (parents.some(parent => pending.some(t => t.name === parent && t.name !== table.name))) continue;
            let ddl = legacyTableSql(String(table.sql));
            if (table.name === 'accounts') ddl = ddl.replace(/CHECK\s*\(skin BETWEEN 0 AND 5\)/i, 'CHECK(skin>=0)');
            await client.query(ddl);
            pending.splice(index, 1); progress = true;
          }
          if (!progress) throw new Error('Cyclic source foreign keys require an explicit migration');
        }
        const remaining = [...tables];
        const imported = new Set<string>();
        const schemaReport = { schema: source.schema, tables: [] as { name: string; count: number; sha256: string }[] };
        while (remaining.length) {
          let progress = false;
          for (let index = remaining.length - 1; index >= 0; index--) {
            const name = String(remaining[index].name);
            const parents = sqlite.prepare('PRAGMA foreign_key_list(' + identifier(name) + ')').all().map(fk => String(fk.table));
            if (parents.some(parent => parent !== name && !imported.has(parent))) continue;
            const rows = sqlite.prepare('SELECT * FROM ' + identifier(name)).all() as DatabaseRow[];
            if (name === 'demo_flight_sessions') {
              await client.query('ALTER TABLE ' + identifier(name) + ' ADD COLUMN sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE');
              const ordering = sqlite.prepare('SELECT rowid AS sequence_id,id FROM ' + identifier(name)).all();
              const positions = new Map(ordering.map(row => [row.id, row.sequence_id]));
              for (const row of rows) row.sequence_id = positions.get(row.id);
            }
            const columns = (sqlite.prepare('PRAGMA table_info(' + identifier(name) + ')').all()).map(col => String(col.name));
            if (name === 'demo_flight_sessions') columns.push('sequence_id');
            for (let start = 0; start < rows.length; start += 250) {
              const chunk = rows.slice(start, start + 250), values: unknown[] = [];
              const tuples = chunk.map(row => '(' + columns.map(col => { values.push(row[col]); return '$' + values.length; }).join(',') + ')');
              await client.query('INSERT INTO ' + identifier(name) + '(' + columns.map(identifier).join(',') + ') VALUES ' + tuples.join(','), values);
            }
            const restored = (await client.query('SELECT * FROM ' + identifier(name))).rows;
            const sha256 = rowsDigest(rows);
            if (rows.length !== restored.length || sha256 !== rowsDigest(restored)) throw new Error('Import verification failed: ' + source.schema + '.' + name);
            schemaReport.tables.push({ name, count: rows.length, sha256 });
            imported.add(name); remaining.splice(index, 1); progress = true;
          }
          if (!progress) throw new Error('Cyclic row dependencies require an explicit migration');
        }
        const indexes = sqlite.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL").all();
        for (const index of indexes) await client.query(String(index.sql));
        if (source.bindingsPath) {
          const config = JSON.parse(String(sqlite.prepare('SELECT config FROM state WHERE id=1').get()!.config));
          const manifest = JSON.parse(await readFile(source.bindingsPath, 'utf8'));
          const configSha256 = createHash('sha256').update(JSON.stringify(config)).digest('hex');
          if (!manifest || Object.keys(manifest).sort().join(',') !== 'asset,bindings,configSha256,network,version'
            || manifest.version !== 1 || manifest.network !== 'nile' || manifest.asset !== 'USDT_NILE_TEST'
            || manifest.configSha256 !== configSha256 || !Array.isArray(manifest.bindings)
            || manifest.bindings.length > config.addresses.length) throw new Error('Invalid legacy Nile bindings');
          await client.query(`CREATE TABLE account_bindings(account_id TEXT PRIMARY KEY,user_id TEXT NOT NULL UNIQUE REFERENCES addresses(user_id),address TEXT NOT NULL,bound_at BIGINT NOT NULL CHECK(bound_at>0))`);
          const rows: DatabaseRow[] = [], accounts = new Set(), users = new Set();
          for (const row of manifest.bindings) {
            if (!row || Object.keys(row).sort().join(',') !== 'accountId,address,boundAt,userId'
              || !gameAccountId(row.accountId) || accounts.has(row.accountId) || users.has(row.userId)
              || !Number.isSafeInteger(row.boundAt) || row.boundAt < 1 || row.boundAt > Date.now() + 30000
              || !config.addresses.some((address: any) => address.userId === row.userId && address.address === row.address)) throw new Error('Invalid legacy Nile binding row');
            accounts.add(row.accountId); users.add(row.userId);
            const restoredRow = { account_id: row.accountId, user_id: row.userId, address: row.address, bound_at: row.boundAt };
            rows.push(restoredRow);
            await client.query('INSERT INTO account_bindings VALUES($1,$2,$3,$4)', Object.values(restoredRow));
          }
          const restored = (await client.query('SELECT * FROM account_bindings')).rows;
          const sha256 = rowsDigest(rows);
          if (rows.length !== restored.length || sha256 !== rowsDigest(restored)) throw new Error('Import verification failed: Nile bindings');
          schemaReport.tables.push({ name: 'account_bindings', count: rows.length, sha256 });
        }
        const identities = await client.query("SELECT table_name,column_name FROM information_schema.columns WHERE table_schema=$1 AND is_identity='YES'", [source.schema]);
        for (const row of identities.rows) await client.query('SELECT setval(pg_get_serial_sequence($1,$2), COALESCE((SELECT MAX(' + identifier(row.column_name) + ') FROM ' + identifier(row.table_name) + '),1), EXISTS(SELECT 1 FROM ' + identifier(row.table_name) + '))', [identifier(source.schema) + '.' + identifier(row.table_name), row.column_name]);
        schemaReport.tables.sort((a, b) => a.name.localeCompare(b.name)); report.push(schemaReport);
      } finally { sqlite.close(); }
    }
    await client.query('COMMIT');
    const result = { ok: true, database: 'postgresql', committedAt: new Date().toISOString(), schemas: report };
    if (reportFile) await writeFile(reportFile, JSON.stringify(result, null, 2) + '\n', { mode: 0o600 });
    return result;
  } catch (error) { await client.query('ROLLBACK').catch(() => {}); throw error; }
  finally { client.release(); await pool.end(); }
}

if (process.argv[1]?.endsWith('database-migrate.ts') || process.argv[1]?.endsWith('database-migrate.js')) {
  const file = process.argv[2];
  if (!file) throw new Error('Usage: database-migrate <source-manifest.json> [report.json]');
  const sources = JSON.parse(await readFile(file, 'utf8')) as Source[];
  const result = await migrateLegacyDatabases(sources, process.argv[3], process.argv[4] ?? '');
  console.log(JSON.stringify(result));
}
