import pg, { type PoolClient, type PoolConfig, type QueryResult } from 'pg';
import { AsyncLocalStorage } from 'node:async_hooks';
import { createHash, randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';

export type DatabaseRow = Record<string, any>;
export const identifier = (name: string) => '"' + name.replaceAll('"', '""') + '"';
const context = new AsyncLocalStorage<Map<PostgresDatabase, { client: PoolClient; readOnly: boolean; lockKey?: string }>>();
const queryQueues = new WeakMap<PoolClient, Promise<unknown>>();
const secret = (name: string, env: NodeJS.ProcessEnv) => env[name + '_FILE'] ? readFileSync(env[name + '_FILE']!, 'utf8').trim() : env[name];

export function databaseConfig(env: NodeJS.ProcessEnv = process.env): PoolConfig {
  const connectionString = secret('DATABASE_URL', env);
  const sslMode = env.PGSSLMODE ?? 'disable';
  if (!['disable', 'verify-full'].includes(sslMode)) throw new Error('PGSSLMODE must be disable or verify-full');
  if (connectionString) {
    const url = new URL(connectionString);
    if (!['postgres:', 'postgresql:'].includes(url.protocol)) throw new Error('DATABASE_URL must use PostgreSQL');
    if ([...url.searchParams.keys()].some(key => /^ssl/i.test(key) || key === 'options')) throw new Error('Configure PostgreSQL TLS with PGSSLMODE');
  } else if (!env.PGHOST || !env.PGDATABASE || !env.PGUSER) {
    throw new Error('Set DATABASE_URL or PGHOST, PGDATABASE and PGUSER. SQLite storage is no longer supported.');
  }
  const max = Number(env.PGPOOL_MAX ?? '10');
  if (!Number.isInteger(max) || max < 1 || max > 50) throw new Error('PGPOOL_MAX must be between 1 and 50');
  const port = Number(env.PGPORT ?? '5432');
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('Invalid PGPORT');
  const milliseconds = (name: string, fallback: number, minimum: number, maximum: number) => {
    const value = Number(env[name] ?? fallback);
    if (!Number.isInteger(value) || value < minimum || value > maximum) throw new Error(name + ' is outside the supported range');
    return value;
  };
  const types = { getTypeParser(oid: number, format?: string) {
    if ([20, 1700].includes(oid)) return (value: string) => {
      const number = Number(value);
      // NUMERIC aggregates can exceed JavaScript precision even when every BIGINT input is safe.
      if (oid === 1700 && (!/^-?\d+$/.test(value) || !Number.isSafeInteger(number))) return value;
      if (!Number.isSafeInteger(number)) throw new Error('PostgreSQL number exceeds safe JavaScript range');
      return number;
    };
    return pg.types.getTypeParser(oid, format as 'text' | 'binary');
  } };
  return { ...(connectionString ? { connectionString } : { host: env.PGHOST, port, database: env.PGDATABASE, user: env.PGUSER, password: secret('PGPASSWORD', env) }),
    max, connectionTimeoutMillis: milliseconds('PGCONNECT_TIMEOUT_MS', 5000, 100, 30000),
    statement_timeout: milliseconds('PGSTATEMENT_TIMEOUT_MS', 15000, 100, 300000),
    lock_timeout: milliseconds('PGLOCK_TIMEOUT_MS', 5000, 100, 30000),
    idle_in_transaction_session_timeout: milliseconds('PGIDLE_TX_TIMEOUT_MS', 90000, 1000, 300000),
    idleTimeoutMillis: milliseconds('PGPOOL_IDLE_MS', 30000, 1000, 600000), allowExitOnIdle: true,
    application_name: env.PGAPPNAME || 'royal', types,
    ssl: sslMode === 'verify-full' ? { rejectUnauthorized: true, ...(env.PGSSLROOTCERT ? { ca: readFileSync(env.PGSSLROOTCERT, 'utf8') } : {}) } : false };
}

// Convert parameter markers only outside SQL literals, identifiers and comments.
export function parameterSql(sql: string) {
  let index = 0;
  return sql.replace(/\$([a-zA-Z_][a-zA-Z_0-9]*)?\$[\s\S]*?\$\1\$|'(?:''|[^'])*'|"(?:""|[^"])*"|--[^\n]*|\/\*[\s\S]*?\*\/|\?/g,
    token => token === '?' ? '$' + (++index) : token);
}

export function legacyTableSql(sql: string) {
  return sql.replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/BIGINT PRIMARY KEY AUTOINCREMENT/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\)\s*STRICT\b/gi, ')')
    .replace(/CHECK\(json_valid\((\w+)\)\)/gi, 'CHECK(($1::jsonb) IS NOT NULL)')
    .replace(/(\w+) NOT GLOB '\*\[\^0-9\]\*'/gi, "$1 !~ '[^0-9]'");
}

function querySql(sql: string) {
  let result = parameterSql(sql);
  if (/^\s*INSERT OR IGNORE\b/i.test(result)) result = result.replace(/INSERT OR IGNORE/i, 'INSERT') + ' ON CONFLICT DO NOTHING';
  result = result.replace(/\bAS ([a-z_][a-z_0-9]*[A-Z][a-zA-Z_0-9]*)\b/g, (_match, alias) => 'AS ' + identifier(alias));
  return result;
}

export type SchemaSnapshot = { format: 'royal-postgres-v1'; schema: string; createdAt: string;
  tables: { name: string; columns: { name: string; type: string; notNull: boolean; default: string | null; identity: string }[]; rows: DatabaseRow[];
    constraints: { name: string; definition: string; kind: string }[]; indexes: string[] }[]; functions: string[]; triggers: string[] };

export function rowsDigest(rows: DatabaseRow[]) {
  const normalized = rows.map(row => JSON.stringify(Object.fromEntries(Object.keys(row).sort().map(key => [key, row[key]])))).sort();
  return createHash('sha256').update(normalized.join('\n')).digest('hex');
}

export class PostgresDatabase {
  readonly pool: pg.Pool;
  readonly schema: string;
  readonly ready: Promise<void>;
  private closed = false;
  get inTransaction() { return context.getStore()?.has(this) ?? false; }
  constructor(name = 'royal_game', private options: { readOnly?: boolean; config?: PoolConfig } = {}) {
    if (name === ':memory:' || !/^[a-z_][a-z0-9_]*$/.test(name)) {
      if (process.env.NODE_ENV !== 'test') throw new Error('Database storage requires a PostgreSQL schema name');
      name = 'test_' + (name === ':memory:' ? randomUUID().replaceAll('-', '') : createHash('sha256').update(name).digest('hex').slice(0, 24));
    }
    this.schema = name;
    const config = options.config ?? databaseConfig();
    this.pool = new pg.Pool({ ...config, application_name: config.application_name === 'royal' ? 'royal/' + name : config.application_name,
      options: '-c search_path=' + identifier(name) + ',public' + (options.readOnly ? ' -c default_transaction_read_only=on' : '') });
    this.pool.on('error', () => { /* Requests report connection failures without leaking credentials. */ });
    this.ready = options.readOnly ? this.pool.query('SELECT 1').then(() => undefined)
      : this.initializeSchema();
    // Store initialization awaits this promise and propagates failures to startup.
    this.ready.catch(() => {});
  }
  private async initializeSchema() {
    const client = await this.pool.connect();
    try {
      await client.query('BEGIN');
      await client.query('SELECT pg_advisory_xact_lock(hashtextextended($1,0))', ['schema:' + this.schema]);
      await client.query('CREATE SCHEMA IF NOT EXISTS ' + identifier(this.schema));
      await client.query('COMMIT');
    } catch (error) { await client.query('ROLLBACK').catch(() => {}); throw error; }
    finally { client.release(); }
  }
  private async query(sql: string, values?: unknown[]): Promise<QueryResult<DatabaseRow>> {
    await this.ready;
    if (this.closed) throw new Error('PostgreSQL store is closed');
    const active = context.getStore()?.get(this);
    if (!active) return this.pool.query(sql, values);
    const previous = queryQueues.get(active.client) ?? Promise.resolve();
    const pending = previous.catch(() => {}).then(() => active.client.query(sql, values));
    queryQueues.set(active.client, pending);
    return pending;
  }
  async exec(sql: string) {
    if (/\b(PRAGMA|VACUUM INTO|BEGIN IMMEDIATE|sqlite_master)\b/i.test(sql)) throw new Error('SQLite SQL is not supported by PostgreSQL');
    await this.query(legacyTableSql(sql));
  }
  prepare(sql: string) {
    const text = querySql(sql);
    return {
      get: async (...values: unknown[]): Promise<DatabaseRow | undefined> => (await this.query(text, values)).rows[0],
      all: async (...values: unknown[]): Promise<DatabaseRow[]> => (await this.query(text, values)).rows,
      run: async (...values: unknown[]) => { const result = await this.query(text, values); return { changes: result.rowCount ?? 0,
        lastInsertRowid: result.rows[0]?.seq ?? result.rows[0]?.id ?? 0 }; },
      iterate: async (...values: unknown[]) => (await this.query(text, values)).rows.values(),
    };
  }
  async transaction<T>(callback: () => Promise<T>, options: { readOnly?: boolean; lockKey?: string } = {}): Promise<T> {
    await this.ready;
    if (this.closed) throw new Error('PostgreSQL store is closed');
    if (options.lockKey !== undefined && (!options.lockKey || options.lockKey.length > 512)) throw new Error('Invalid transaction lock key');
    const active = context.getStore()?.get(this);
    if (active) {
      if (options.lockKey !== undefined && active.lockKey !== options.lockKey) throw new Error('Nested transactions must use the same lock key');
      return callback();
    }
    const client = await this.pool.connect();
    try {
      await client.query(options.readOnly ? 'BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY' : 'BEGIN');
      if (!options.readOnly) await client.query('SELECT pg_advisory_xact_lock(hashtextextended($1, 0))',
        [options.lockKey === undefined ? this.schema : this.schema + ':key:' + options.lockKey]);
      const connections = new Map(context.getStore());
      connections.set(this, { client, readOnly: !!options.readOnly, lockKey: options.lockKey });
      const result = await context.run(connections, callback);
      await client.query('COMMIT');
      return result;
    } catch (error) { await client.query('ROLLBACK').catch(() => {}); throw error; }
    finally { client.release(); }
  }
  async hasTable(name: string) { return !!(await this.query('SELECT 1 FROM information_schema.tables WHERE table_schema=$1 AND table_name=$2', [this.schema, name])).rows[0]; }
  async columns(name: string) { return (await this.query('SELECT column_name AS name, data_type AS type FROM information_schema.columns WHERE table_schema=$1 AND table_name=$2 ORDER BY ordinal_position', [this.schema, name])).rows; }
  async triggers() { return (await this.query('SELECT t.tgname AS name FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND NOT t.tgisinternal ORDER BY t.tgname', [this.schema])).rows.map(row => String(row.name)); }
  async integrityCheck() {
    const invalid = await this.query('SELECT conname FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace WHERE n.nspname=$1 AND NOT convalidated', [this.schema]);
    if (invalid.rows.length) throw new Error('Unvalidated PostgreSQL constraints');
    return true;
  }
  async exportSnapshot(): Promise<SchemaSnapshot> {
    return this.transaction(async () => {
      const tables: SchemaSnapshot['tables'] = [];
      const names = await this.query("SELECT tablename AS name FROM pg_tables WHERE schemaname=$1 ORDER BY tablename", [this.schema]);
      for (const { name } of names.rows) {
        const reg = identifier(this.schema) + '.' + identifier(name);
        const columns = await this.query(`SELECT a.attname AS name, format_type(a.atttypid,a.atttypmod) AS type, a.attnotnull AS "notNull", pg_get_expr(d.adbin,d.adrelid) AS "default", a.attidentity AS identity
          FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum WHERE a.attrelid=$1::regclass AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum`, [reg]);
        const constraints = await this.query('SELECT conname AS name, pg_get_constraintdef(oid) AS definition, contype AS kind FROM pg_constraint WHERE conrelid=$1::regclass ORDER BY conname', [reg]);
        const indexes = await this.query('SELECT indexdef FROM pg_indexes i WHERE schemaname=$1 AND tablename=$2 AND NOT EXISTS(SELECT 1 FROM pg_constraint c WHERE c.conindid=(quote_ident(i.schemaname)||\'.\'||quote_ident(i.indexname))::regclass)', [this.schema, name]);
        tables.push({ name, columns: columns.rows as any, rows: (await this.query('SELECT * FROM ' + reg)).rows, constraints: constraints.rows as any, indexes: indexes.rows.map(row => row.indexdef) });
      }
      const functions = await this.query("SELECT pg_get_functiondef(p.oid) AS definition FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname=$1 AND p.prokind='f' ORDER BY p.proname", [this.schema]);
      const triggers = await this.query('SELECT pg_get_triggerdef(t.oid) AS definition FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND NOT t.tgisinternal ORDER BY t.tgname', [this.schema]);
      return { format: 'royal-postgres-v1', schema: this.schema, createdAt: new Date().toISOString(), tables, functions: functions.rows.map(row => row.definition), triggers: triggers.rows.map(row => row.definition) };
    }, { readOnly: true });
  }
  async snapshot(file: string) {
    const snapshot = await this.exportSnapshot();
    await writeFile(file, JSON.stringify(snapshot) + '\n', { flag: 'wx', mode: 0o600 });
    return snapshot;
  }
  static async restore(file: string, schema = 'restore_' + randomUUID().replaceAll('-', '')) {
    const snapshot = JSON.parse(await readFile(file, 'utf8')) as SchemaSnapshot;
    if (snapshot.format !== 'royal-postgres-v1' || !Array.isArray(snapshot.tables)) throw new Error('Invalid PostgreSQL snapshot');
    const db = new PostgresDatabase(schema);
    const remap = (sql: string) => sql.replaceAll(identifier(snapshot.schema) + '.', identifier(schema) + '.').replaceAll(snapshot.schema + '.', identifier(schema) + '.');
    try {
      await db.transaction(async () => {
        if ((await db.query('SELECT 1 FROM pg_tables WHERE schemaname=$1', [schema])).rows.length) throw new Error('Restore target must be empty');
        for (const table of snapshot.tables) {
          const cols = table.columns.map(col => identifier(col.name) + ' ' + col.type + (col.identity ? ' GENERATED BY DEFAULT AS IDENTITY' : col.default && !col.default.includes('nextval(') ? ' DEFAULT ' + remap(col.default) : '') + (col.notNull ? ' NOT NULL' : ''));
          await db.exec('CREATE TABLE ' + identifier(table.name) + '(' + cols.join(',') + ')');
          for (const row of table.rows) {
            const keys = Object.keys(row);
            await db.prepare('INSERT INTO ' + identifier(table.name) + '(' + keys.map(identifier).join(',') + ') VALUES(' + keys.map(() => '?').join(',') + ')').run(...keys.map(key => row[key]));
          }
          if (rowsDigest((await db.prepare('SELECT * FROM ' + identifier(table.name)).all())) !== rowsDigest(table.rows)) throw new Error('Snapshot row verification failed');
        }
        for (const kind of ['p', 'u', 'c', 'f']) for (const table of snapshot.tables) for (const constraint of table.constraints.filter(c => c.kind === kind)) {
          await db.exec('ALTER TABLE ' + identifier(table.name) + ' ADD CONSTRAINT ' + identifier(constraint.name) + ' ' + remap(constraint.definition));
        }
        for (const table of snapshot.tables) {
          for (const index of table.indexes) await db.exec(remap(index));
          for (const col of table.columns.filter(c => c.identity)) await db.prepare("SELECT setval(pg_get_serial_sequence(?,?), COALESCE((SELECT MAX(" + identifier(col.name) + ') FROM ' + identifier(table.name) + "),1), EXISTS(SELECT 1 FROM " + identifier(table.name) + '))').get(identifier(schema) + '.' + identifier(table.name), col.name);
        }
        for (const fn of snapshot.functions) await db.exec(remap(fn));
        for (const trigger of snapshot.triggers) await db.exec(remap(trigger));
      });
      return db;
    } catch (error) { await db.dropSchema().catch(() => {}); await db.close(); throw error; }
  }
  async dropSchema() { await this.query('DROP SCHEMA ' + identifier(this.schema) + ' CASCADE'); }
  async close() { if (!this.closed) { await this.ready.catch(() => {}); this.closed = true; await this.pool.end(); } }
}
